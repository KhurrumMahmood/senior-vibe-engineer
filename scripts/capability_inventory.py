"""Generate a portable lookup of first-party capabilities in a host project.

The shared source inventory decides which files and languages exist. This tool
adds two intentionally bounded facts: a description harvested from each
source file's own documentation, and statically resolved first-party
references where the language has an honest local resolver.
"""

